"""Honest capability status for the UI and the delivery path. Read-only view of catalog/capability_status.json (built from the Phase 4/5 evidence by scripts/build_capability_status.py).

A status is never inferred from a catalog tier label. `block(sourcetype)` is the single rule for "this selection must not generate":
no working generator, a metric/event routing conflict with the add-on, or events that do not match the add-on's extraction rules.
"""
import json
import os
from typing import Any, Dict, List, Optional

_CACHE: Optional[Dict[str, Any]] = None
ORDER = {"VERIFIED": 0, "FORMAT_CHECKED": 1, "GENERATOR_UNVERIFIED": 2, "UNSUPPORTED": 3}


def _path() -> str:
    here = os.path.dirname(os.path.abspath(__file__))
    for base in (os.path.join(here, "catalog_data"), os.path.join(os.path.dirname(here), "catalog_data"), os.path.join(os.path.dirname(os.path.dirname(here)), "catalog"),
                 os.path.join(os.path.dirname(here), "catalog")):
        p = os.path.join(base, "capability_status.json")
        if os.path.exists(p):
            return p
    raise FileNotFoundError("capability_status.json not found next to the catalog data")


def data() -> Dict[str, Any]:
    global _CACHE
    if _CACHE is None:
        with open(_path(), encoding="utf-8") as f:
            _CACHE = json.load(f)
    return _CACHE


def get(sourcetype: str) -> Optional[Dict[str, Any]]:
    return data()["sourcetypes"].get(sourcetype)


def block(sourcetype: str) -> Optional[Dict[str, str]]:
    r = get(sourcetype)
    return r["block"] if r else None


def routing_block(sourcetype: str) -> Optional[Dict[str, str]]:
    b = block(sourcetype)
    return b if b and b["code"] == "ROUTING_CONFLICT" else None


def tree(verified_only: bool = False) -> List[Dict[str, Any]]:
    """vendor -> product -> sourcetypes, best-status first, so verified integrations lead."""
    vendors: Dict[str, Dict[str, Any]] = {}
    for r in data()["sourcetypes"].values():
        if verified_only and r["status"] != "VERIFIED":
            continue
        v = vendors.setdefault(r["vendor_id"], {"id": r["vendor_id"], "name": r["vendor"], "products": {}})
        p = v["products"].setdefault(r["product"], {"name": r["product"], "sourcetypes": []})
        p["sourcetypes"].append({k: r[k] for k in ("sourcetype", "kind", "status", "status_label", "notes", "block", "ta", "generator") if k in r} | ({"evidence": r["evidence"]} if "evidence" in r else {}))
    out = []
    for v in vendors.values():
        prods = list(v["products"].values())
        for p in prods:
            p["sourcetypes"].sort(key=lambda s: (ORDER[s["status"]], s["sourcetype"]))
            p["best"] = min(ORDER[s["status"]] for s in p["sourcetypes"])
        prods.sort(key=lambda p: (p["best"], p["name"]))
        out.append({"id": v["id"], "name": v["name"], "best": min(p["best"] for p in prods), "products": prods})
    out.sort(key=lambda v: (v["best"], v["name"].lower(), v["id"]))
    return out


def scenario(row: Dict[str, Any]) -> Dict[str, Any]:
    """Eligibility of one scenario. `runnable` = every required sourcetype has a working delivery path and the scenario itself is runnable;
    `verified` = every required sourcetype is Verified in Splunk (a different, much stronger claim)."""
    reqs, blocked, unknown = [], [], []
    for st in row["sourcetypes"]:
        c = get(st)
        if c is None:
            unknown.append(st)
            reqs.append({"sourcetype": st, "status": "GENERATOR_UNVERIFIED", "status_label": data()["labels"]["GENERATOR_UNVERIFIED"], "note": "not a catalog sourcetype; generated by the scenario's own engine"})
            continue
        if c["block"] and c["block"]["code"] == "NO_GENERATOR":
            # the standalone sourcetype picker has no generator for it, but a scenario engine may build it itself: not a reason to refuse the scenario
            reqs.append({"sourcetype": st, "status": "GENERATOR_UNVERIFIED", "status_label": data()["labels"]["GENERATOR_UNVERIFIED"], "block": None,
                         "note": "generated by the scenario's own engine; there is no standalone generator for it and its parsing in Splunk is untested"})
            continue
        reqs.append({"sourcetype": st, "status": c["status"], "status_label": c["status_label"], "block": c["block"]})
        if c["block"] and c["block"]["code"] == "ROUTING_CONFLICT":
            blocked.append((st, c["block"]["message"]))
    reasons = []
    if not row["catalog_runnable"]:
        reasons.append(row["catalog_blocked_reason"] or "This scenario is not runnable in this build.")
    reasons += ["%s: %s" % b for b in blocked]
    runnable = not reasons
    verified = runnable and bool(reqs) and all(r["status"] == "VERIFIED" for r in reqs)
    incompatible = [r["sourcetype"] for r in reqs if r.get("block") and r["block"]["code"] == "PAYLOAD_CONFLICT"]
    return {"id": row["id"], "title": row["title"], "category": row["category"], "summary": row["summary"], "engine": row["engine"], "dashboard": row["dashboard"], "required": reqs, "runnable": runnable,
            "verified": verified, "run_state": ("VERIFIED_IN_SPLUNK" if verified else "RUNNABLE_UNVERIFIED" if runnable else "NOT_RUNNABLE"), "reasons": reasons,
            "warnings": (["These required sourcetypes do not match their add-on's extraction rules: " + ", ".join(incompatible)] if incompatible else []),
            "worst_status": max((r["status"] for r in reqs), key=lambda s: ORDER[s], default="UNSUPPORTED")}


def scenarios() -> List[Dict[str, Any]]:
    out = [scenario(r) for r in data()["scenarios"]]
    out.sort(key=lambda s: ({"VERIFIED_IN_SPLUNK": 0, "RUNNABLE_UNVERIFIED": 1, "NOT_RUNNABLE": 2}[s["run_state"]], s["title"].lower()))
    return out
